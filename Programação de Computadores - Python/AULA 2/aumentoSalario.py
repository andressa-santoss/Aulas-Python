# Exercicio aumento de 5 por cento num salario 


salario = float(input("Digite o valor do seu salario:  "))

# Calculo da porcentagem (5%  ---> * 0.5)
comissao = salario *0.5

# calculo do salario com a comissão
calculoAumento = salario + comissao

print("O salario com a comissão é de R$ ", calculoAumento)